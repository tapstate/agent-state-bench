"""Write the three DAB datasets of the freshness extension, one per arm (FRESHNESS.md §3):

  query_bank_fresh_direct     D: the six live source systems (the static setup A's databases, with
                              core_banking replayed live)
  query_bank_fresh_live       U/C: bank_live, a continuous mirror of Tapstate's view
  query_bank_fresh_warehouse  U/P: bank_warehouse, Tapstate's view copied once a night

Each gets db_config.yaml, its description and query1..query24 (query.json, ground_truth.csv,
validate.py). Each arm is told its own freshness truthfully. The consolidated arms' dump folders
hold the rewind state; with DAB_PERSISTENT_DBS=1 DAB loads a dump only if the database is missing,
and the driver keeps both databases present.

Usage: python make_fresh_datasets.py <dab-root>
"""
import json
import sys
from pathlib import Path

from fresh_common import COLLECTION, DATASETS, HERE, LIVE_DB, META, QUESTIONS, WAREHOUSE_DB
import timeline as tl
from common import DATASET, consolidated_doc, load_customers
from make_queries import gt_lines
from split_sources import write_mongo_dump

DESCRIPTIONS = HERE.parent / "descriptions"

LIVE_NOTE = ("They are the bank's live systems: every transaction is visible in them as soon as it is posted.")
UC_FROM = "maintained continuously from the bank's"
UC_TO = "kept continuously up to date, as changes are made, from the bank's"
UP_TO = "loaded once a night, at 00:00 IST, from the bank's"
UP_NOTE = ("It does not include changes made in those systems since the last load. The `_meta` collection "
           "holds one document, whose `loaded_at` field is the date and time (IST) of the last load.")

VALIDATE = '''"""Bank freshness question {id} ({kind}, {sim_time}). Generated by make_fresh_datasets.py; do not edit."""
import re

SPEC = {spec}
DATETIME = re.compile({datetime!r})

{checker}

def validate(llm_output: str):
    # dates and times are removed first: every question states the current time (fresh_check.py)
    if holds(SPEC, DATETIME.sub(" ", llm_output)):
        return True, "Expected answer found: " + describe(SPEC)
    return False, "Expected answer not found: " + describe(SPEC)
'''


def descriptions():
    a = (DESCRIPTIONS / "setup_a.txt").read_text()
    first, rest = a.split("\n", 1)
    direct = first + " " + LIVE_NOTE + "\n" + rest
    c = (DESCRIPTIONS / "setup_c.txt").read_text()
    assert UC_FROM in c and "bank_state" in c
    live = c.replace("bank_state", LIVE_DB).replace(UC_FROM, UC_TO)
    para_end = c.index("\n", c.index(UC_FROM))
    warehouse = (c[:para_end] + " " + UP_NOTE + c[para_end:]).replace(UC_FROM, UP_TO).replace(
        "holds the consolidated current state", "holds the consolidated state").replace("bank_state", WAREHOUSE_DB)
    warehouse = warehouse.replace(f"Collection in {WAREHOUSE_DB}:", f"Collections in {WAREHOUSE_DB}:")
    warehouse = warehouse.rstrip("\n") + f"\n- {META}: one document; fields loaded_at\n"
    return {"D": direct, "UC": live, "UP": warehouse}


def config(arm):
    if arm == "D":
        return (Path(sys.argv[1]).resolve() / f"query_{DATASET}" / "db_config.yaml").read_text()
    db = LIVE_DB if arm == "UC" else WAREHOUSE_DB
    return (f"db_clients:\n  {db}:\n    db_type: mongo\n    db_name: {db}\n"
            f"    dump_folder: query_dataset/{db}_dump\n")


def rewind_docs():
    cs = tl.state_at(load_customers(), set())
    return [{"_id": cid, **consolidated_doc(cid, rec)} for cid, rec in cs.items()]


def main():
    dab = Path(sys.argv[1]).resolve()
    qs = json.loads(QUESTIONS.read_text())
    checker = (HERE.parent / "answer_check.py").read_text().split('"""', 2)[2].strip()
    from fresh_check import DATETIME
    descs, docs = descriptions(), rewind_docs()
    for arm, ds in DATASETS.items():
        base = dab / f"query_{ds}"
        base.mkdir(exist_ok=True)
        (base / "db_config.yaml").write_text(config(arm))
        (base / "db_description.txt").write_text(descs[arm])
        (base / "db_description_withhint.txt").write_text("")
        data = base / "query_dataset"
        if arm == "D":
            if not data.exists():
                data.symlink_to(dab / f"query_{DATASET}" / "query_dataset")
        else:
            db = LIVE_DB if arm == "UC" else WAREHOUSE_DB
            colls = {COLLECTION: docs}
            if arm == "UP":
                colls[META] = [{"_id": "load", "loaded_at": tl.sim_time(tl.load_time(0))}]
            write_mongo_dump(data / f"{db}_dump", db, colls)
        for q in qs:
            # rewrite only these three files: a query directory also holds the runs' logs
            d = base / f"query{q['id']}"
            d.mkdir(exist_ok=True)
            (d / "query.json").write_text(json.dumps(q["text"], ensure_ascii=False))
            (d / "ground_truth.csv").write_text("\n".join(gt_lines(q["answer"])) + "\n")
            (d / "validate.py").write_text(VALIDATE.format(
                id=q["id"], kind=q["kind"], sim_time=q["sim_time"], spec=repr(q["answer"]),
                datetime=DATETIME.pattern, checker=checker))
    print(f"wrote {len(qs)} questions to " + ", ".join(f"query_{d}" for d in DATASETS.values()))


if __name__ == "__main__":
    main()
