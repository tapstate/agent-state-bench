"""Write the 24 questions as DAB query directories, for setups A/B and for setup C.

Each queryN/ gets query.json (the question), ground_truth.csv (the reference answer, one value
per line) and validate.py (answer_check.py plus this question's spec, self-contained, as DAB's
validator loader imports it on its own). The same three files go to query_bank and
query_bank_consolidated, so every setup is scored identically. Also writes questions.json, a
frozen record of questions, categories, systems and answers.

Usage: python make_queries.py <dab-root>
"""
import json
import shutil
import sys
from pathlib import Path

from answer_check import describe
from common import CONSOLIDATED, DATASET, HERE
from questions import build

VALIDATE = '''"""Bank pilot question {id} ({category}). Generated by make_queries.py; do not edit."""
SPEC = {spec}

{checker}

def validate(llm_output: str):
    if holds(SPEC, llm_output):
        return True, "Expected answer found: " + describe(SPEC)
    return False, "Expected answer not found: " + describe(SPEC)
'''


def gt_lines(spec):
    kind = spec[0]
    if kind in ("count", "money", "text"):
        return [describe(spec)]
    if kind == "ids":
        return list(spec[1])
    if kind == "labeled":
        return [f"{l[0] if isinstance(l, list) else l}: {describe(s)}" for l, s in spec[1]]
    return [x for s in spec[1] for x in gt_lines(s)]


def main():
    dab = Path(sys.argv[1]).resolve()
    qs = build()
    checker = (HERE / "answer_check.py").read_text().split('"""', 2)[2].strip()
    for ds in (DATASET, CONSOLIDATED):
        base = dab / f"query_{ds}"
        ids = {f"query{q['id']}" for q in qs}
        for old in base.glob("query[0-9]*"):
            if old.name not in ids:
                shutil.rmtree(old)
        for q in qs:
            # rewrite only this script's three files: a query directory also holds the runs' logs
            d = base / f"query{q['id']}"
            d.mkdir(parents=True, exist_ok=True)
            (d / "query.json").write_text(json.dumps(q["text"], ensure_ascii=False))
            (d / "ground_truth.csv").write_text("\n".join(gt_lines(q["answer"])) + "\n")
            (d / "validate.py").write_text(VALIDATE.format(id=q["id"], category=q["category"],
                                                           spec=repr(json.loads(json.dumps(q["answer"]))),
                                                           checker=checker))
    (HERE / "questions.json").write_text(json.dumps(qs, indent=1, ensure_ascii=False) + "\n")
    print(f"wrote {len(qs)} questions to query_{DATASET} and query_{CONSOLIDATED}")


if __name__ == "__main__":
    main()
